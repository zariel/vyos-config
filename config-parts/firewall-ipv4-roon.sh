#!/bin/vbash

set firewall ipv4 name roon-local rule 50 action 'accept'
set firewall ipv4 name roon-local rule 50 description 'DHCP requests'
set firewall ipv4 name roon-local rule 50 protocol 'udp'
set firewall ipv4 name roon-local rule 50 source port '68'
set firewall ipv4 name roon-local rule 50 destination port '67'
set firewall ipv4 name local-roon rule 50 action 'accept'
set firewall ipv4 name local-roon rule 50 description 'DHCP replies'
set firewall ipv4 name local-roon rule 50 protocol 'udp'
set firewall ipv4 name local-roon rule 50 source port '67'
set firewall ipv4 name local-roon rule 50 destination port '68'

set firewall ipv4 name roon-local rule 60 action 'accept'
set firewall ipv4 name roon-local rule 60 description 'Gateway NTP'
set firewall ipv4 name roon-local rule 60 protocol 'udp'
set firewall ipv4 name roon-local rule 60 destination address '10.5.0.10'
set firewall ipv4 name roon-local rule 60 destination port '123'

set firewall ipv4 name roon-local rule 100 action 'accept'
set firewall ipv4 name roon-local rule 100 description 'IGMP membership reports'
set firewall ipv4 name roon-local rule 100 protocol 'igmp'

set firewall ipv4 name roon-local rule 110 action 'accept'
set firewall ipv4 name roon-local rule 110 description 'Rule: accept_mdns'
set firewall ipv4 name roon-local rule 110 destination port 'mdns'
set firewall ipv4 name roon-local rule 110 destination address '224.0.0.251'
set firewall ipv4 name roon-local rule 110 protocol 'udp'
set firewall ipv4 name local-roon rule 110 action 'accept'
set firewall ipv4 name local-roon rule 110 description 'Rule: accept_mdns'
set firewall ipv4 name local-roon rule 110 destination port 'mdns'
set firewall ipv4 name local-roon rule 110 destination address '224.0.0.251'
set firewall ipv4 name local-roon rule 110 protocol 'udp'
set firewall ipv4 name local-roon rule 100 action 'accept'
set firewall ipv4 name local-roon rule 100 description 'IGMP membership queries'
set firewall ipv4 name local-roon rule 100 protocol 'igmp'

set firewall ipv4 name roon-transit rule 10 action 'accept'
set firewall ipv4 name roon-transit rule 10 description 'Internal DNS'
set firewall ipv4 name roon-transit rule 10 protocol 'tcp_udp'
set firewall ipv4 name roon-transit rule 10 destination address '10.254.253.53'
set firewall ipv4 name roon-transit rule 10 destination port '53'

set firewall ipv4 name roon-transit rule 20 action 'accept'
set firewall ipv4 name roon-transit rule 20 description 'ROCK to NAS SMB'
set firewall ipv4 name roon-transit rule 20 protocol 'tcp'
set firewall ipv4 name roon-transit rule 20 source address '10.1.4.10'
set firewall ipv4 name roon-transit rule 20 destination group address-group 'STORAGE'
set firewall ipv4 name roon-transit rule 20 destination port '445'

set firewall ipv4 name transit-roon rule 100 action 'accept'
set firewall ipv4 name transit-roon rule 100 description 'Pods to the Roon Core API'
set firewall ipv4 name transit-roon rule 100 protocol 'tcp'
set firewall ipv4 name transit-roon rule 100 source group network-group 'POD_NETS'
set firewall ipv4 name transit-roon rule 100 destination address '10.1.4.10'
set firewall ipv4 name transit-roon rule 100 destination port '9330'

set firewall ipv4 name transit-roon rule 110 action 'accept'
set firewall ipv4 name transit-roon rule 110 description 'Pods to the Bluesound player API'
set firewall ipv4 name transit-roon rule 110 protocol 'tcp'
set firewall ipv4 name transit-roon rule 110 source group network-group 'POD_NETS'
set firewall ipv4 name transit-roon rule 110 destination address '10.1.4.13-10.1.4.14'
set firewall ipv4 name transit-roon rule 110 destination port '11000'

set firewall ipv4 name roon-wan rule 100 action 'accept'
set firewall ipv4 name roon-wan rule 100 description 'Music services and firmware updates'
set firewall ipv4 name roon-wan rule 100 protocol 'tcp'
set firewall ipv4 name roon-wan rule 100 destination port '80,443'

# Trusted clients, including WireGuard peers, may reach every ROON device:
# Roon control and ARC, ROCK administration and the BluOS app.
set firewall ipv4 name trusted-roon rule 100 action 'accept'
set firewall ipv4 name trusted-roon rule 100 description 'Allow Trusted to ROON'

# Replies to relayed discovery can be unicast to the client's sending socket.
set firewall ipv4 name roon-trusted rule 120 action 'accept'
set firewall ipv4 name roon-trusted rule 120 description 'ROCK discovery replies to Trusted LAN'
set firewall ipv4 name roon-trusted rule 120 outbound-interface name 'bond0.20'
set firewall ipv4 name roon-trusted rule 120 protocol 'udp'
set firewall ipv4 name roon-trusted rule 120 source address '10.1.4.10'
set firewall ipv4 name roon-trusted rule 120 source port '9003'
